/** Helper: bytes -> hex string */
function bytesToHex(u8: Uint8Array): string {
  let s = '';
  for (let i = 0; i < u8.length; i++) {
    const h = u8[i].toString(16).padStart(2, '0');
    s += h;
  }
  return s;
}

